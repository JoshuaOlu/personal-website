#!/usr/bin/env ruby
# Reads the podcast feed named in _data/podcast.yml and writes _data/podcast_feed.yml.
# GitHub runs this before every build. To try it yourself: ruby scripts/sync_podcast.rb
# Test with a saved feed:  ruby scripts/sync_podcast.rb --file feed.xml
require 'yaml'
require 'net/http'
require 'uri'
require 'time'
require 'rexml/document'

ROOT = File.expand_path('..', __dir__)
cfg = YAML.safe_load(File.read(File.join(ROOT, '_data', 'podcast.yml'))) || {}
out = File.join(ROOT, '_data', 'podcast_feed.yml')
file_arg = ARGV.index('--file') && ARGV[ARGV.index('--file') + 1]
feed = cfg['feed_url'].to_s.strip

if feed.empty? && file_arg.nil?
  File.write(out, "# generated, do not edit\nshow: {}\nepisodes: []\n") unless File.exist?(out) && File.read(out).include?('episodes: []')
  puts 'No podcast feed set. Nothing to sync.'
  exit 0
end

def fetch(url, limit = 5)
  raise 'Too many redirects' if limit.zero?
  uri = URI(url)
  raise 'Feed must be https' unless uri.scheme == 'https'
  res = Net::HTTP.start(uri.host, uri.port, use_ssl: true, open_timeout: 15, read_timeout: 30) do |h|
    h.get(uri.request_uri, 'User-Agent' => 'joshua.olunlade.com podcast sync')
  end
  case res
  when Net::HTTPSuccess then res.body.force_encoding('UTF-8')
  when Net::HTTPRedirection then fetch(URI.join(url, res['location']).to_s, limit - 1)
  else raise "Feed returned #{res.code}"
  end
end

def text(el)
  return '' unless el
  el.texts.map(&:value).join.strip
end

def clean(html, max = 600)
  t = html.to_s.gsub(/<[^>]*>/, ' ').gsub(/&nbsp;/, ' ').gsub('&amp;', '&').gsub('&lt;', '<').gsub('&gt;', '>').gsub('&quot;', '"').gsub('&#39;', "'")
  t = t.gsub(/\s+/, ' ').strip
  t.length > max ? t[0, max - 1].sub(/\s+\S*\z/, '') + '…' : t
end

begin
  xml = file_arg ? File.read(file_arg) : fetch(feed)
  doc = REXML::Document.new(xml)
  ch = doc.elements['rss/channel'] or raise 'This does not look like a podcast feed'
  image = nil
  ch.each_element('*') { |e| image = e.attributes['href'] if e.name == 'image' && e.attributes['href'] }
  image ||= text(ch.elements['image/url'])
  show = { 'title' => text(ch.elements['title']), 'description' => clean(text(ch.elements['description']), 500),
           'link' => text(ch.elements['link']), 'image' => image.to_s }
  eps = []
  ch.each_element('item') do |it|
    enc = it.elements['enclosure']
    next unless enc && enc.attributes['url']
    next unless enc.attributes['url'].start_with?('https://')
    dur = nil; season = nil; num = nil; img = nil
    it.each_element('*') do |e|
      case e.name
      when 'duration' then dur = text(e)
      when 'season' then season = text(e)
      when 'episode' then num = text(e)
      when 'image' then img = e.attributes['href']
      end
    end
    desc = text(it.elements['description'])
    desc = it.elements['*[local-name()="encoded"]'] ? text(it.elements['*[local-name()="encoded"]']) : desc if desc.empty?
    date = (Time.parse(text(it.elements['pubDate'])).utc rescue nil)
    link = text(it.elements['link'])
    eps << { 'title' => text(it.elements['title']), 'date' => date ? date.strftime('%Y-%m-%d') : nil,
             'summary' => clean(desc), 'audio' => enc.attributes['url'],
             'link' => link.start_with?('https://') ? link : '', 'duration' => dur.to_s,
             'season' => season.to_s, 'episode' => num.to_s, 'image' => img.to_s }
  end
  eps = eps.first((cfg['max_episodes'] || 100).to_i)
  File.write(out, "# generated by scripts/sync_podcast.rb, do not edit\n" + { 'show' => show, 'episodes' => eps }.to_yaml.sub(/\A---\n/, ''))
  puts "Synced #{eps.size} episodes from #{show['title']}."
rescue StandardError => e
  # Never break the site build because a feed is down: keep whatever we had.
  warn "Podcast sync failed: #{e.message}. Keeping the previous list."
  File.write(out, "# generated, do not edit\nshow: {}\nepisodes: []\n") unless File.exist?(out)
  exit 0
end
